/**
 * Returns localized string for given key.
 * Fallback priority: current lang -> 'en' -> 'uz' -> ''
 */
export function getLandingText(key, lang = 'en') {
  const item = landingTranslations[key];
  if (!item) return '';
  return item[lang] || item['en'] || item['uz'] || '';
}

/**
 * Formats pricing breakdown line with exact symmetry.
 */
export function getPricingBreakdown(lang = 'en', displayCount = 1, additionalCost = '0.00') {
  if (displayCount <= 1) {
    if (lang === 'ru') {
      return {
        baseLabel: 'Базовая цена: ',
        baseAmount: '$16.95',
        extraText: ' (1 преподаватель / админ)'
      };
    }
    if (lang === 'en') {
      return {
        baseLabel: 'Base price: ',
        baseAmount: '$16.95',
        extraText: ' (1 teacher / admin)'
      };
    }
    return {
      baseLabel: 'Asosiy narx: ',
      baseAmount: '$16.95',
      extraText: ' (1 ta oʻqituvchi / admin)'
    };
  }

  const extraCount = displayCount - 1;
  if (lang === 'ru') {
    return {
      baseLabel: 'Базовый: ',
      baseAmount: '$16.95',
      extraText: ` + Дополнительно ${extraCount} сотрудников: `,
      extraAmount: `+$${additionalCost}`
    };
  }
  if (lang === 'en') {
    return {
      baseLabel: 'Base: ',
      baseAmount: '$16.95',
      extraText: ` + Additional ${extraCount} team staff: `,
      extraAmount: `+$${additionalCost}`
    };
  }
  return {
    baseLabel: 'Asosiy: ',
    baseAmount: '$16.95',
    extraText: ` + Qoʻshimcha ${extraCount} ta xodim: `,
    extraAmount: `+$${additionalCost}`
  };
}
