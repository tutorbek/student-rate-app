/**
 * Normalizes any icon or avatar key:
 * If it's a legacy local path (/avatar_image/...), gallery ID (img_1), or contains image hash,
 * it returns the fast direct CDN link (https://i.postimg.cc/...).
 */
export const normalizeIconUrl = (key) => {
  if (!key || typeof key !== 'string') return key;

  // Direct web URL already
  if (key.startsWith('http://') || key.startsWith('https://')) {
    return key;
  }

  // Check by gallery item ID (e.g. 'img_1')
  const byId = AVATAR_GALLERY_IMAGES.find((img) => img.id === key);
  if (byId) return byId.path;

  // Check by legacy local path or matching file hash
  const found = AVATAR_GALLERY_IMAGES.find((img) => {
    if (img.legacyPath === key) return true;
    if (key.includes(img.name)) return true;
    return false;
  });
  if (found) return found.path;

  return key;
};

export const isGalleryImage = (key) => {
  if (!key || typeof key !== 'string') return false;
  return (
    key.startsWith('https://i.postimg.cc/') ||
    key.startsWith('https://postimg.cc/') ||
    key.startsWith('/avatar_image/') ||
    AVATAR_GALLERY_IMAGES.some(
      (img) => img.path === key || img.legacyPath === key || img.id === key || key.includes(img.name)
    )
  );
};

/**
 * Resize and compress user-uploaded image files on client-side canvas
 * to max 128x128 JPEG (~3-4KB) before storing, preventing Base64 bloating in JSON.
 */
export const compressUploadedImage = (file, maxDimension = 128, quality = 0.75) => {
  return new Promise((resolve, reject) => {
    if (!file) {
      resolve(null);
      return;
    }
    const reader = new FileReader();
    reader.onload = (event) => {
      const img = new Image();
      img.onload = () => {
        const canvas = document.createElement('canvas');
        let width = img.width;
        let height = img.height;

        if (width > height) {
          if (width > maxDimension) {
            height = Math.round((height * maxDimension) / width);
            width = maxDimension;
          }
        } else {
          if (height > maxDimension) {
            width = Math.round((width * maxDimension) / height);
            height = maxDimension;
          }
        }

        canvas.width = width;
        canvas.height = height;
        const ctx = canvas.getContext('2d');
        ctx.drawImage(img, 0, 0, width, height);

        // Export as lightweight JPEG data URL
        const compressedDataUrl = canvas.toDataURL('image/jpeg', quality);
        resolve(compressedDataUrl);
      };
      img.onerror = (err) => reject(err);
      img.src = event.target.result;
    };
    reader.onerror = (err) => reject(err);
    reader.readAsDataURL(file);
  });
};
